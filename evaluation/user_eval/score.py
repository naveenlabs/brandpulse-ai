"""Score the private response file against PROTOCOL.md and write aggregate results.

Read-only on the responses. Re-run after every new participant:  python evaluation/user_eval/score.py
"""
import re
import statistics
from pathlib import Path

HERE = Path(__file__).parent

# PROTOCOL.md, "Answer key: the 17 comprehension items". Fixed 24 Sep 2026, before any response.
KEY = {"S1": "c", "L1": "a", "R3": "b", "R4": "b", "R6": "b", "R7": "b", "R8": "a", "R9": "a",
       "R11": "b", "R12": "a", "R14": "b", "M1": "a", "M2": "b", "M3": "d", "M7": "a", "M9": "b",
       "M10": "b"}
LIKERT = ["F2", "S2", "R5", "R10", "R15", "M4", "M5", "M8", "O3", "O4"]
CHOICE_EXTRA = ["A1", "A2", "A3", "A4", "L2", "D1", "D2", "D3", "D4", "D5"]

# R9's key is the 0:40 card's own sentence. That sentence is false: the stored channel labels
# for seg 7 are transcript NEGATIVE, vocal NEUTRAL, comment POSITIVE (outputs/analysis/
# "Apple (Duo).json", facts.moments), and the note says the voice read positive. The key is
# kept as registered; R9 is reported both ways so the fault is visible, not scored away.
INVALID = {"R9": "keyed to a moment note that misstates the voice channel (vocal NEUTRAL, note says positive)"}


def parse(text):
    """{participant: {item: answer}} from the fenced blocks under '## P<n>'."""
    people = {}
    for m in re.finditer(r"^## (P\d+)\n.*?```text\n(.*?)```", text, re.S | re.M):
        answers = {}
        for item, ans in re.findall(r"^\[([A-Z]\d+[a-z]?|C0\.\d)\][^\n]*\n-> ([^\n]*)", m.group(2), re.M):
            answers[item] = ans.strip()
        people[m.group(1)] = answers
    return people


def letter(ans):
    m = re.match(r"([a-z])\) ", ans)
    return m.group(1) if m else None


def likert(ans):
    m = re.match(r"(\d) of 5", ans)
    return int(m.group(1)) if m else None


def main():
    response_file = HERE / "RESPONSES.md"
    if not response_file.exists():
        raise SystemExit(
            "RESPONSES.md is private research data and is not included in the public repository."
        )
    people = parse(response_file.read_text())
    ids = sorted(people, key=lambda p: int(p[1:]))
    n = len(ids)
    out = [f"# Final user evaluation: scores (generated by `score.py`, n = {n})", "",
           "Generated from privately held responses using the key and rules in `PROTOCOL.md`.", ""]

    out += ["## Comprehension, per item", "",
            "| Item | Key | " + " | ".join(ids) + " | Correct | Not sure |",
            "|---|---|" + "---|" * n + "---|---|"]
    per_person = {p: [0, 0] for p in ids}          # [correct on 17, correct excluding invalid]
    flagged = []
    for item, key in KEY.items():
        row, right, unsure = [], 0, 0
        for p in ids:
            a = people[p].get(item, "")
            ok = letter(a) == key
            ns = "Not sure" in a
            right += ok
            unsure += ns
            per_person[p][0] += ok
            per_person[p][1] += ok and item not in INVALID
            row.append("✓" if ok else ("?" if ns else f"✗ {letter(a)}"))
        mark = " †" if item in INVALID else ""
        out.append(f"| {item}{mark} | {key} | " + " | ".join(row) + f" | {right} of {n} | {unsure} of {n} |")
        if n - right >= 2:
            flagged.append(f"{item} ({n - right} of {n} not correct)")
    out += ["", "✓ correct · ✗ wrong (letter chosen) · ? Not sure (neither right nor wrong)", ""]
    for item, why in INVALID.items():
        out.append(f"† {item}: {why}.")
    out += ["", "## Comprehension, per participant", "",
            "| | " + " | ".join(ids) + " | Median |", "|---|" + "---|" * n + "---|"]
    s17 = [per_person[p][0] for p in ids]
    s16 = [per_person[p][1] for p in ids]
    out.append("| Correct of 17 (as registered) | " + " | ".join(map(str, s17)) + f" | {statistics.median(s17)} |")
    out.append(f"| Correct of {17 - len(INVALID)} (without †) | " + " | ".join(map(str, s16)) + f" | {statistics.median(s16)} |")
    out += ["", "**Items with 2 or more not correct (the protocol's pattern rule):** "
            + (", ".join(flagged) if flagged else "none"), ""]

    out += ["## Likert items (1 to 5)", "", "| Item | " + " | ".join(ids) + " | Median |",
            "|---|" + "---|" * n + "---|"]
    for item in LIKERT:
        vals = [likert(people[p].get(item, "")) for p in ids]
        got = [v for v in vals if v is not None]
        med = statistics.median(got) if got else "—"
        out.append(f"| {item} | " + " | ".join("—" if v is None else str(v) for v in vals) + f" | {med} |")

    out += ["", "## Other choices", "", "| Item | " + " | ".join(ids) + " |", "|---|" + "---|" * n]
    for item in CHOICE_EXTRA:
        out.append(f"| {item} | " + " | ".join(people[p].get(item, "—") for p in ids) + " |")
    (HERE / "SCORES.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
